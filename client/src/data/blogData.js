// Helper function to get a post by ID
export const getBlogPostById = (id) => {
  return blogPosts.find(post => post.id === parseInt(id))
}

// Helper function to get related posts (excluding the current post)
export const getRelatedPosts = (currentPostId, limit = 3) => {
  return blogPosts
    .filter(post => post.id !== parseInt(currentPostId))
    .slice(0, limit)
}

// Helper function to get featured posts
export const getFeaturedPosts = () => {
  return blogPosts.filter(post => post.featured)
}

// Helper function to get trending posts (sorted by views)
export const getTrendingPosts = (limit = 3) => {
  return [...blogPosts].sort((a, b) => b.views - a.views).slice(0, limit)
}